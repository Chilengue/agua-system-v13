-- Pagamento (total ou parcial) com recibo; pode cobrir várias faturas
CREATE TABLE payments (
    id_payment BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_company_payment BIGINT NOT NULL,
    id_customer_payment BIGINT NOT NULL,
    receipt_number_payment VARCHAR(30) NOT NULL,
    amount_payment NUMERIC(14,2) NOT NULL,
    method_payment VARCHAR(20) NOT NULL DEFAULT 'cash',
    reference_payment VARCHAR(120),
    paid_at_payment TIMESTAMP NOT NULL,
    client_uuid_payment VARCHAR(40) UNIQUE,
    status_payment VARCHAR(12) NOT NULL DEFAULT 'confirmed',
    notes_payment TEXT,
    id_user_payment BIGINT,
    validated_by_payment BIGINT,
    validated_at_payment TIMESTAMP,
    voided_by_payment BIGINT,
    voided_at_payment TIMESTAMP,
    void_reason_payment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_method_payment CHECK (method_payment IN ('cash', 'mpesa', 'emola', 'mkesh', 'bank', 'card', 'other')),
    CONSTRAINT ck_status_payment CHECK (status_payment IN ('pending', 'confirmed', 'voided'))
);

-- Parte de um pagamento aplicada a uma fatura
