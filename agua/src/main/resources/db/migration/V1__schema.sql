    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_company_user BIGINT,
    id_customer_user BIGINT,
    name_user VARCHAR(150) NOT NULL,
    username_user VARCHAR(60) NOT NULL UNIQUE,
    email_user VARCHAR(150),
    phone_user VARCHAR(40),
    password_user VARCHAR(255) NOT NULL,
    role_user VARCHAR(12) NOT NULL,
    status_user VARCHAR(12) NOT NULL DEFAULT 'active',
    must_change_password_user BOOLEAN NOT NULL DEFAULT false,
    last_login_user TIMESTAMP,
