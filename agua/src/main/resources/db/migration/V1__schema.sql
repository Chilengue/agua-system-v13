-- Empresa / provedor de água (tenant). code = AGUA-XXXX-XXXX
CREATE TABLE companies (
    id_company BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_company VARCHAR(20) NOT NULL UNIQUE,
    name_company VARCHAR(180) NOT NULL,
    nuit_company VARCHAR(32),
    phone_company VARCHAR(40),
    email_company VARCHAR(150),
    address_company TEXT,
    city_company VARCHAR(120),
    province_company VARCHAR(120),
    slogan_company VARCHAR(200),
    logo_company TEXT,
    status_company VARCHAR(12) NOT NULL DEFAULT 'pending',
    self_registered_company BOOLEAN NOT NULL DEFAULT false,
    approved_at_company TIMESTAMP,
    notes_company TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_status_company CHECK (status_company IN ('pending', 'active', 'suspended', 'rejected'))
);

