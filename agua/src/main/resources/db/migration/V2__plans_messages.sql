-- ---------- 1. Plano de cada empresa ----------
--   basic      → Básico: sem WhatsApp e sem SMS
--   standard   → Standard: avisos e recibos por WhatsApp
--   enterprise → Enterprise: WhatsApp + SMS
ALTER TABLE companies ADD COLUMN plan_company VARCHAR(12) NOT NULL DEFAULT 'basic';
ALTER TABLE companies ADD COLUMN plan_changed_at_company TIMESTAMP;
ALTER TABLE companies ADD CONSTRAINT ck_plan_company CHECK (plan_company IN ('basic', 'standard', 'enterprise'));

-- ---------- 2. Números e regras de mensagens de cada empresa ----------
ALTER TABLE company_settings ADD COLUMN whatsapp_number_company_setting VARCHAR(40);
ALTER TABLE company_settings ADD COLUMN whatsapp_mode_company_setting VARCHAR(10) NOT NULL DEFAULT 'link';
ALTER TABLE company_settings ADD COLUMN whatsapp_phone_id_company_setting VARCHAR(60);
ALTER TABLE company_settings ADD COLUMN whatsapp_token_company_setting TEXT;
ALTER TABLE company_settings ADD COLUMN sms_number_company_setting VARCHAR(40);
ALTER TABLE company_settings ADD COLUMN sms_mode_company_setting VARCHAR(10) NOT NULL DEFAULT 'link';
ALTER TABLE company_settings ADD COLUMN sms_api_url_company_setting VARCHAR(300);
ALTER TABLE company_settings ADD COLUMN sms_api_token_company_setting TEXT;
ALTER TABLE company_settings ADD COLUMN msg_channel_company_setting VARCHAR(10) NOT NULL DEFAULT 'whatsapp';
ALTER TABLE company_settings ADD COLUMN msg_on_invoice_company_setting BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE company_settings ADD COLUMN msg_on_payment_company_setting BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE company_settings ADD COLUMN msg_invoice_template_company_setting TEXT;
ALTER TABLE company_settings ADD COLUMN msg_payment_template_company_setting TEXT;
ALTER TABLE company_settings ADD COLUMN msg_reminder_template_company_setting TEXT;
ALTER TABLE company_settings ADD CONSTRAINT ck_whatsapp_mode_company_setting CHECK (whatsapp_mode_company_setting IN ('link', 'api'));
ALTER TABLE company_settings ADD CONSTRAINT ck_sms_mode_company_setting CHECK (sms_mode_company_setting IN ('link', 'api'));
ALTER TABLE company_settings ADD CONSTRAINT ck_msg_channel_company_setting CHECK (msg_channel_company_setting IN ('whatsapp', 'sms', 'both'));

-- ---------- 3. Mensagens enviadas (ou preparadas para envio manual) ----------
-- status: queued (na fila da API) · manual (aberta no WhatsApp/SMS do operador) · sent · failed · cancelled
CREATE TABLE messages (
    id_message BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_company_message BIGINT NOT NULL,
    id_customer_message BIGINT,
    channel_message VARCHAR(10) NOT NULL,
    kind_message VARCHAR(12) NOT NULL DEFAULT 'custom',
    id_ref_message BIGINT,
    to_phone_message VARCHAR(40) NOT NULL,
    body_message TEXT NOT NULL,
    status_message VARCHAR(10) NOT NULL DEFAULT 'queued',
    attempts_message INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    provider_ref_message VARCHAR(120),
    sent_at_message TIMESTAMP,
    id_user_message BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_channel_message CHECK (channel_message IN ('whatsapp', 'sms')),
    CONSTRAINT ck_kind_message CHECK (kind_message IN ('invoice', 'payment', 'reminder', 'custom')),
    CONSTRAINT ck_status_message CHECK (status_message IN ('queued', 'manual', 'sent', 'failed', 'cancelled'))
);
ALTER TABLE messages ADD CONSTRAINT fk_id_company_message FOREIGN KEY (id_company_message) REFERENCES companies(id_company);
ALTER TABLE messages ADD CONSTRAINT fk_id_customer_message FOREIGN KEY (id_customer_message) REFERENCES customers(id_customer);
CREATE INDEX ix_messages_company_date ON messages (id_company_message, created_at);
CREATE INDEX ix_messages_queue ON messages (status_message, id_message) WHERE status_message = 'queued';
CREATE INDEX ix_messages_customer ON messages (id_customer_message);

-- ---------- 4. Melhorias na base de dados ----------
-- Valores que nunca podem ser negativos (protege contra erros de programa ou importações)
ALTER TABLE payments ADD CONSTRAINT ck_amount_payment CHECK (amount_payment > 0);
ALTER TABLE payment_allocations ADD CONSTRAINT ck_amount_payment_allocation CHECK (amount_payment_allocation > 0);
ALTER TABLE invoices ADD CONSTRAINT ck_total_invoice CHECK (total_invoice >= 0 AND paid_amount_invoice >= 0);
ALTER TABLE readings ADD CONSTRAINT ck_consumption_reading CHECK (consumption_reading >= 0 AND current_value_reading >= 0);
ALTER TABLE meters ADD CONSTRAINT ck_initial_reading_meter CHECK (initial_reading_meter >= 0);
ALTER TABLE tariff_tiers ADD CONSTRAINT ck_price_m3_tariff_tier CHECK (price_m3_tariff_tier >= 0);

-- Ligações que faltavam: pagamentos e leituras do mesmo cliente/empresa, mediador da leitura.
-- (Um cliente com leituras, faturas ou pagamentos nunca pode ser apagado: as chaves estrangeiras impedem-no.)
ALTER TABLE readings ADD CONSTRAINT fk_id_user_reading FOREIGN KEY (id_user_reading) REFERENCES users(id_user);
ALTER TABLE payment_allocations ADD CONSTRAINT fk_id_company_payment_allocation FOREIGN KEY (id_company_payment_allocation) REFERENCES companies(id_company);
ALTER TABLE audit_logs ADD CONSTRAINT fk_id_company_audit_log FOREIGN KEY (id_company_audit_log) REFERENCES companies(id_company);

